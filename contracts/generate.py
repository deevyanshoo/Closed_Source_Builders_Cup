#!/usr/bin/env python3
"""Generate wire types from the authoritative OpenAPI subset. No runtime coercion."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / 'contracts/openapi.yaml').read_text())


def typename(schema, lang):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    choices = schema.get('oneOf', schema.get('anyOf'))
    if choices:
        nonnull = [s for s in choices if s.get('type') != 'null']
        if len(nonnull) == 1 and len(nonnull) != len(choices):
            return typename(nonnull[0], lang) + ' | null' if lang == 'ts' else '*' + typename(nonnull[0], lang)
        return ' | '.join(typename(s, lang) for s in choices) if lang == 'ts' else 'json.RawMessage'
    kind = schema.get('type')
    if isinstance(kind, list):
        return 'string | null' if lang == 'ts' else '*string'
    if 'const' in schema and lang == 'ts':
        return json.dumps(schema['const']).lower()
    if 'enum' in schema and lang == 'ts':
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if kind == 'array':
        inner = typename(schema['items'], lang)
        return '(' + inner + ')[]' if lang == 'ts' else '[]' + inner
    return {'string': 'string', 'integer': 'number' if lang == 'ts' else 'int',
            'boolean': 'boolean' if lang == 'ts' else 'bool'}[kind]


def render():
    ts = ['// Generated by contracts/generate.py; do not edit.\n']
    has_union = any('oneOf' in schema for schema in SPEC['components']['schemas'].values())
    go = ['// Code generated by contracts/generate.py; DO NOT EDIT.\npackage contract\n' + ('\nimport \"encoding/json\"\n' if has_union else '')]
    for name, schema in SPEC['components']['schemas'].items():
        if 'properties' not in schema and ('oneOf' in schema or 'anyOf' in schema):
            ts.append('export type ' + name + ' = ' + typename(schema, 'ts') + ';\n')
            go.append('type ' + name + ' = ' + typename(schema, 'go') + '\n')
            continue
        ts.append('export interface ' + name + ' {')
        go.append('type ' + name + ' struct {')
        required = schema.get('required', [])
        for field, sub in schema['properties'].items():
            optional = field not in required
            ts.append('  ' + field + ('?' if optional else '') + ': ' + typename(sub, 'ts') + ';')
            goname = ''.join(part.title() for part in field.split('_'))
            gotype = typename(sub, 'go')
            if optional and not gotype.startswith('*'):
                gotype = '*' + gotype
            go.append('  ' + goname + ' ' + gotype + ' `json:"' + field + (',omitempty' if optional else '') + '"`')
        ts.append('}\n')
        go.append('}\n')
    result = {'contracts/generated/types.ts': '\n'.join(ts),
              'services/gateway/internal/contract/types.go': '\n'.join(go)}
    operation = SPEC['paths'].get('/v2/production/receipt-recovery/comparisons', {}).get('post')
    if operation:
        selected = {}
        def collect(name):
            if name in selected:
                return
            schema = SPEC['components']['schemas'][name]
            selected[name] = schema
            def walk(value):
                if isinstance(value, dict):
                    if '$ref' in value:
                        collect(value['$ref'].split('/')[-1])
                    for item in value.values():
                        walk(item)
                elif isinstance(value, list):
                    for item in value:
                        walk(item)
            walk(schema)
        for name in ('RecoveryComparisonRequest', 'RecoveryComparisonResponse', 'RecoveryComparisonUnsupportedResponse'):
            collect(name)
        data = {'components': {'schemas': selected}, 'limits': {
            'request_bytes': operation['x-request-max-bytes'],
            'response_bytes': operation['x-response-max-bytes'],
            'max_depth': operation['x-max-depth']}}
        encoded = json.dumps(data, indent=2) + '\n'
        result['services/gateway/internal/contract/recovery_schema.json'] = encoded
        result['procurement-engine/src/procure/production/recovery_http_schema.json'] = encoded
        result['contracts/generated/recovery-schema.ts'] = '// Generated by contracts/generate.py; do not edit.\nexport const recoverySchema = ' + json.dumps(data) + ';\n'
        examples = {name: json.loads((ROOT / ('contracts/examples/' + name + '_request.json')).read_text()) for name in ('recovery', 'recovery_precision')}
        result['contracts/generated/recovery-examples.ts'] = '// Generated by contracts/generate.py; do not edit.\nimport type { RecoveryComparisonRequest } from \"./types\";\nexport const recoveryExamples: Record<string, RecoveryComparisonRequest> = ' + json.dumps(examples) + ';\n'
    voice = SPEC['paths'].get('/v2/voice/sessions', {}).get('post')
    if voice:
        selected = {}
        def collect_voice(name):
            if name in selected:
                return
            schema = SPEC['components']['schemas'][name]
            selected[name] = schema
            def walk(value):
                if isinstance(value, dict):
                    if '$ref' in value:
                        collect_voice(value['$ref'].split('/')[-1])
                    for child in value.values():
                        walk(child)
                elif isinstance(value, list):
                    for child in value:
                        walk(child)
            walk(schema)
        for name in ('VoiceHTTPSessionRequest', 'VoiceHTTPTurnRequest', 'VoiceHTTPSessionResponse', 'VoiceHTTPTurnResponse', 'VoiceHTTPCancelResponse', 'VoiceHTTPCloseResponse', 'VoiceHTTPResultResponse', 'StateErrorResponse'):
            collect_voice(name)
        data = {'components': {'schemas': selected}, 'limits': {'session_request_bytes': voice['x-request-max-bytes'], 'turn_request_bytes': SPEC['paths']['/v2/voice/sessions/{session_id}/turns']['post']['x-request-max-bytes'], 'response_bytes': voice['x-response-max-bytes'], 'max_depth': voice['x-max-depth'], 'max_array_items': voice['x-max-array-items'], 'total_array_items': voice['x-total-array-items']}}
        result['services/gateway/internal/contract/voice_http_schema.json'] = json.dumps(data, indent=2) + '\n'
        result['contracts/generated/voice-http-schema.ts'] = '// Generated by contracts/generate.py; do not edit.\nexport const voiceHTTPSchema = ' + json.dumps(data) + ';\n'
        result['contracts/generated/voice-http-client.ts'] = voice_client()
    return result


def voice_client():
    """Typed local transport helper only; credentials/context remain host-owned."""
    return "// Generated by contracts/generate.py; do not edit.\nimport type { VoiceHTTPSessionRequest, VoiceHTTPSessionResponse, VoiceHTTPTurnRequest, VoiceHTTPTurnResponse, VoiceHTTPCancelResponse, VoiceHTTPCloseResponse, VoiceHTTPResultResponse, StateErrorResponse } from './types';\nexport class VoiceHTTPError extends Error {\n  constructor(public readonly status: number, public readonly response: StateErrorResponse) { super(response.error.message); }\n}\n// A trusted caller supplies an existing development credential; no credential is generated or persisted here.\nexport function createVoiceHTTPClient(baseURL: string, bearer: () => string, transport: typeof fetch = fetch) {\n  const path = '/v2/voice/sessions';\n  async function request<T>(method: string, suffix: string, body?: unknown): Promise<T> {\n    const headers: Record<string, string> = { Authorization: 'Bearer ' + bearer() };\n    if (body !== undefined) headers['Content-Type'] = 'application/json';\n    const response = await transport(baseURL + path + suffix, { method, headers, cache: 'no-store', body: body === undefined ? undefined : JSON.stringify(body) });\n    const value = await response.json();\n    if (!response.ok) throw new VoiceHTTPError(response.status, value as StateErrorResponse);\n    return value as T;\n  }\n  const session = (id: string) => '/' + encodeURIComponent(id);\n  const turn = (id: string, tid: string) => session(id) + '/turns/' + encodeURIComponent(tid);\n  return {\n    create: (body: VoiceHTTPSessionRequest) => request<VoiceHTTPSessionResponse>('POST', '', body),\n    start: (id: string, body: VoiceHTTPTurnRequest) => request<VoiceHTTPTurnResponse>('POST', session(id) + '/turns', body),\n    cancel: (id: string, tid: string) => request<VoiceHTTPCancelResponse>('POST', turn(id, tid) + '/cancel'),\n    result: (id: string, tid: string) => request<VoiceHTTPResultResponse>('GET', turn(id, tid) + '/result'),\n    close: (id: string) => request<VoiceHTTPCloseResponse>('DELETE', session(id)),\n  };\n}\n"


if __name__ == '__main__':
    import sys
    for rel, content in render().items():
        path = ROOT / rel
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Generated file differs: ' + rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('Generated wire types match OpenAPI' if '--check' in sys.argv else 'Generated TypeScript and Go wire types')
